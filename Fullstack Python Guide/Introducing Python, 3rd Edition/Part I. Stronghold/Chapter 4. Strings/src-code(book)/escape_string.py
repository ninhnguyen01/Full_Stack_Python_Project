# Escape with \
# Python lets you escape the meaning of some characters within strings to achieve effects that would otherwise 
# be difficult to express. By preceding a character with a backslash (\), you give it a special meaning. 
# The most common escape sequence is \n, which means to begin a new line. 
# With this, you can create multiline strings from a one-line string

palindrome = 'A man,\nA plan,\nA canal:\nPanama.'
print(palindrome)